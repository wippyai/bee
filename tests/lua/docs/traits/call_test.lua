local test = require("test")
local funcs = require("funcs")
local security = require("security")
local bounds = require("bounds")
local function call(scope: string, tool: string, request: unknown): {[string]: unknown}
    local actor = assert(security.new_actor("trait-tools-test"))
    local policy = assert(security.policy(scope))
    local executor = assert(assert(funcs.new():with_actor(actor)):with_scope(security.new_scope({policy})))
    local result, err = executor:call(tool, request)
    assert(not err, tostring(err))
    return assert(bounds.object(result))
end
local function define_tests()
    test.describe("Scoped trait adapters", function()
        test.it("reads documentation through the tool's declared scope", function()
            local result = call("bee.security.gateway:gateway_tool_docs_policy", "bee.docs.traits:call", {operation = "list", limit = 1})
            test.is_true(result.ok)
        end)
        test.it("keeps delivery and publication operations separate", function()
            local delivery = call("bee.security.gateway:gateway_tool_delivery_policy", "bee.gov.traits:delivery_call", {operation = "publish"})
            test.is_false(delivery.ok)
            test.eq(delivery.code, "DENIED")
            local publication = call("bee.security.gateway:gateway_tool_publish_policy", "bee.gov.traits:publish_call", {operation = "request"})
            test.is_false(publication.ok)
            test.eq(publication.code, "DENIED")
        end)
    end)
end
return {run = test.run_cases(define_tests)}
