-- MIT. Resolver failures remain definite across the Hub and approval boundaries.
local test = require("test")
local hub_result = require("hub_result")
local installation = require("installation")
local function define_tests()
    test.describe("Hub result diagnostics", function()
        test.it("bounds a resolver failure without losing its code or receipt", function()
            local message = "dependency resolution failed: bee/worker@X, Y: " .. string.rep("conflicting roots; ", 500)
            local receipt = {state = "failed", code = "FAILED", message = "saved resolver failure"}
            local decoded = hub_result.decode({ok = false, replayed = false, code = "FAILED", message = message, value = receipt})
            test.eq(decoded.ok, false)
            test.eq(decoded.code, "FAILED")
            test.eq(decoded.value, receipt)
            local shown = decoded.message or ""
            test.eq(#shown, 4096)
            test.is_true(shown:find("dependency resolution failed", 1, true) == 1)
            test.is_true(shown:find("[truncated]", 1, true) ~= nil)
            local status = installation.status(decoded)
            test.eq(status.status, "failed")
            test.eq(status.code, "FAILED")
            test.eq(status.message, shown)
            local effect = installation.effect_result(decoded)
            test.eq(effect.ok, false)
            test.eq(effect.code, "FAILED")
            test.eq(effect.message, shown)
        end)
        test.it("preserves a definite failure when its diagnostics are malformed", function()
            local decoded = hub_result.decode({ok = false, replayed = true, code = "FAILED", message = {invalid = true}})
            test.eq(decoded.ok, false)
            test.eq(decoded.code, "FAILED")
            test.eq(decoded.replayed, true)
            test.eq(decoded.message, "invalid Hub result message")
        end)
        test.it("truncates between UTF-8 characters", function()
            local message = hub_result.message(string.rep("é", 3000)) or ""
            test.is_true(#message <= 4096)
            test.eq(message:sub(1, #message - #" [truncated]"), string.rep("é", 2042))
        end)
        test.it("preserves bounded replies and actual uncertainty", function()
            local decoded = hub_result.decode({ok = false, replayed = false, code = "UNCERTAIN", message = "reply lost"})
            test.eq(decoded.code, "UNCERTAIN")
            test.eq(decoded.message, "reply lost")
            test.eq(hub_result.message(string.rep("x", 4096)), string.rep("x", 4096))
        end)
    end)
end
return test.run_cases(define_tests)
