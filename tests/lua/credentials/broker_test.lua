-- MIT. Focused broker test cases.
local test = require("test")
local registry = require("registry")
local support = require("support")
local fresh = support.fresh
local admit_sources = support.admit_sources
local shipped_sources = assert(registry.get("bee.credentials.env:credential_sources"))
local original_file_policy = assert(registry.get("bee.credentials.security:credential_file_policy"))
local original_write_policy = assert(registry.get("bee.credentials.security:credential_file_write_policy"))
local function define_tests()
    test.describe("Credential broker", function()
        test.after_all(function()
            local restore = assert(registry.snapshot()):changes()
            assert(restore:update(shipped_sources))
            assert(restore:update(original_file_policy))
            assert(restore:update(original_write_policy))
            assert(restore:apply())
        end)
        local workspace = fresh("ws")
        admit_sources(workspace)
        require("broker_environment_cases").define(workspace, shipped_sources)
        require("broker_login_cases").define(workspace)
        require("broker_setup_cases").define(workspace)
        require("broker_secrecy_cases").define(workspace)
    end)
end
return test.run_cases(define_tests)
