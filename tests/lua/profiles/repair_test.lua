local test = require("test")
local form = require("form")
local editor = require("editor")
local registry = require("registry")
local bounds = require("bounds")
local json = require("json")
type Object = {[string]: unknown}
local function replace(id: string, data: unknown)
    local entry = assert(registry.get(id))
    entry.data = data
    local changes = registry.snapshot():changes()
    assert(changes:update(entry)); assert(changes:apply())
end
local function define_tests()
    test.describe("Profile definition repair", function()
        test.it("preserves saved drafts and CAS revision when the definition becomes invalid", function()
            local ref = "bee.driver.claude.profiles:default_window"
            local opened = assert(form.load("profile-repair", {definition_ref = ref, title = "Repair me"}, true))
            assert(form.save(opened))
            local original = assert(json.encode(assert(registry.get(ref)).data))
            replace(ref, {schema_revision = "invalid"})
            local loaded, err = form.load("profile-repair", {saved_profile_id = opened.profile_id, saved_profile_revision = 1, title = "Repair me"}, false)
            replace(ref, assert(json.decode(original)))
            if not loaded then error(tostring(err)) end
            test.eq(loaded.profile_id, opened.profile_id)
            test.eq(loaded.revision, 1)
            test.not_nil(loaded.repair_json)
            test.not_nil(loaded.migration_diagnostic)
            test.eq(assert(bounds.object(json.decode(assert(loaded.repair_json)))).name, "Repair me")
            test.is_true(form.save(loaded))
        end)
        test.it("refreshes runtime options while preserving an unsaved name and save identity", function()
            local opened = assert(form.load("profile-refresh", {definition_ref = "bee.driver.claude.profiles:default_window", title = "Original"}, true))
            assert(editor.set_title(opened.draft, "Unsaved"))
            local refreshed = assert(form.refresh(opened))
            test.eq(refreshed.draft.name, "Unsaved")
            test.eq(refreshed.save_key, opened.save_key)
            test.eq(refreshed.profile_id, opened.profile_id)
            test.eq(refreshed.revision, opened.revision)
        end)
    end)
end
return test.run_cases(define_tests)
