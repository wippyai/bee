-- MIT. The session message draft: typed text, inline and collapsed pastes,
-- chip editing, the byte bound and the read-only chip preview.
local test = require("test")
local message_draft = require("message_draft")
local protocol = require("protocol")
type Event = {[string]: unknown}
local function key(name: string, value: string?, ctrl: boolean?): Event
    return {type = "key", action = "press", key_type = name, key = value or "", ctrl = ctrl == true}
end
local function typed(value: string): Event return {type = "key", action = "press", key_type = "rune", key = value} end
local function pasted(value: string): Event return {type = "paste", text = value} end
local function lines(count: integer): string
    local rows: {string} = {}
    for index = 1, count do rows[index] = "log line " .. tostring(index) end
    return table.concat(rows, "\n") .. "\n"
end
local function draft(): message_draft.Draft return message_draft.new(protocol.MAX_INPUT_BYTES, true) end
local function define_tests()
    test.describe("Session message draft", function()
        test.it("edits typed text by character at its cursor and clears it", function()
            local value = draft()
            message_draft.edit(value, typed("h"))
            message_draft.edit(value, typed("é"))
            test.eq(message_draft.text(value), "hé")
            message_draft.edit(value, key("backspace"))
            test.eq(message_draft.text(value), "h")
            message_draft.edit(value, pasted("ello"))
            message_draft.edit(value, key("home"))
            message_draft.edit(value, typed(">"))
            message_draft.edit(value, key("delete"))
            test.eq(message_draft.text(value), ">ello")
            test.eq(message_draft.line(value, 40), ">▏ello")
            message_draft.edit(value, key("rune", "u", true))
            test.is_true(message_draft.empty(value))
        end)
        test.it("keeps a paste of a few short lines inline", function()
            local value = draft()
            message_draft.edit(value, pasted("one\r\ntwo\rthree"))
            test.eq(message_draft.text(value), "one\ntwo\nthree")
            test.eq(message_draft.line(value, 40), "one↵two↵three▏")
            test.is_nil(message_draft.selected(value))
        end)
        test.it("holds a long paste as one chip showing only its label and sends its full text in place", function()
            local value = draft()
            local log = lines(120)
            message_draft.edit(value, typed("a"))
            message_draft.edit(value, pasted(log))
            message_draft.edit(value, typed("b"))
            test.eq(message_draft.text(value), "a" .. log .. "b")
            local label = "[Pasted text #1 · 120 lines · " .. string.format("%.1f KB", #log / 1024) .. "]"
            test.eq(message_draft.line(value, 200), "a" .. label .. "b▏")
            test.is_nil((message_draft.line(value, 200):find("log line", 1, true)))
            local wide = draft()
            message_draft.edit(wide, pasted(string.rep("x", message_draft.CHIP_BYTES + 1)))
            test.eq(message_draft.line(wide, 200), "[Pasted text #1 · 1 line · 801 B]▏")
        end)
        test.it("numbers chips in order and removes one whole with Backspace after it or Delete before it", function()
            local value = draft()
            local first, second = lines(10), lines(20)
            message_draft.edit(value, pasted(first))
            message_draft.edit(value, typed(" and "))
            message_draft.edit(value, pasted(second))
            test.contains(message_draft.line(value, 200), "[Pasted text #1 · 10 lines")
            test.contains(message_draft.line(value, 200), "[Pasted text #2 · 20 lines")
            test.eq(message_draft.text(value), first .. " and " .. second)
            message_draft.edit(value, key("backspace"))
            test.eq(message_draft.text(value), first .. " and ")
            message_draft.edit(value, key("home"))
            message_draft.edit(value, key("delete"))
            test.eq(message_draft.text(value), " and ")
            test.eq(message_draft.line(value, 200), "▏ and ")
        end)
        test.it("takes text up to its bound and refuses a larger paste or keystroke, saying why and how big", function()
            local value = draft()
            local log = lines(2000)
            test.is_true(message_draft.edit(value, pasted(log)))
            test.eq(message_draft.text(value), log)
            local full = message_draft.new(protocol.MAX_INPUT_BYTES, true, string.rep("x", protocol.MAX_INPUT_BYTES - 2))
            local changed, reason = message_draft.edit(full, pasted(lines(10)))
            test.is_false(changed)
            test.eq(#message_draft.text(full), protocol.MAX_INPUT_BYTES - 2)
            test.contains(tostring(reason), tostring(#lines(10)) .. " bytes")
            test.contains(tostring(reason), tostring(protocol.MAX_INPUT_BYTES))
            local exact = message_draft.new(protocol.MAX_INPUT_BYTES, true, string.rep("x", protocol.MAX_INPUT_BYTES))
            local _, typed_reason = message_draft.edit(exact, typed("y"))
            test.eq(#message_draft.text(exact), protocol.MAX_INPUT_BYTES)
            test.not_nil(typed_reason)
            local name = message_draft.new(5, false, "abc")
            local _, name_reason = message_draft.edit(name, pasted("defg"))
            test.eq(message_draft.text(name), "abc")
            test.contains(tostring(name_reason), "5")
        end)
        test.it("keeps a long paste inline in a draft without chips", function()
            local name = message_draft.new(protocol.MAX_INPUT_BYTES, false)
            message_draft.edit(name, pasted(lines(5)))
            test.contains(message_draft.line(name, 400), "log line 5")
        end)
        test.it("keeps the cursor in view of a line wider than its room", function()
            local value = message_draft.new(protocol.MAX_INPUT_BYTES, true, string.rep("a", 50) .. string.rep("b", 50))
            test.eq(message_draft.line(value, 21), string.rep("b", 20) .. "▏")
            for _ = 1, 50 do message_draft.edit(value, key("left")) end
            local shown = message_draft.line(value, 21)
            test.contains(shown, "a▏b")
            test.eq(#shown, 20 + #"▏")
        end)
        test.it("selects the chip after the cursor, shows its text read-only and closes it", function()
            local value = draft()
            local log = lines(40)
            message_draft.edit(value, pasted(log))
            test.is_false(message_draft.open(value))
            message_draft.edit(value, key("left"))
            test.eq(assert(message_draft.selected(value)).number, 1)
            test.is_true(message_draft.open(value))
            test.eq(assert(value.shown).text, log)
            test.is_true(message_draft.preview_input(value, key("down")))
            test.is_true(message_draft.preview_input(value, key("pgdown")))
            test.eq(value.offset, 11)
            test.is_true(message_draft.preview_input(value, typed("x")))
            test.is_true(message_draft.preview_input(value, pasted("y")))
            test.eq(message_draft.text(value), log)
            test.is_true(message_draft.preview_input(value, key("esc")))
            test.is_nil(value.shown)
            test.is_false(message_draft.preview_input(value, key("down")))
        end)
    end)
end
return test.run_cases(define_tests)
