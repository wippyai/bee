local test = require("test")
local registry = require("registry")
local catalog = require("catalog")
local bounds = require("bounds")
local CLAUDE = "bee.driver.claude.binding:binding"
local CODEX = "bee.driver.codex.binding:binding"
local function cases()
    test.describe("Selected launch catalog", function()
        test.it("classifies only the selected driver's group and still enforces the catalog limit", function()
            local pinned = assert(catalog.pin())
            local selected = assert(catalog.read(pinned, nil, CLAUDE))
            test.eq(#selected.bindings, 1)
            test.eq(selected.bindings[1].binding_id, CLAUDE)
            test.eq(selected.bindings[1].state, "compatible")
            test.is_false(assert(catalog.read(pinned, 1, CLAUDE)).complete)
        end)
        test.it("keeps competing bindings in the selected group so ambiguity still refuses launch", function()
            local original = assert(registry.get(CODEX))
            local changed = assert(registry.get(CODEX))
            assert(bounds.object(changed.meta)).driver_id = "claude"
            local changes = assert(registry.snapshot()):changes()
            changes:update(changed)
            assert(changes:apply())
            local ok, failure = pcall(function()
                local selected = assert(catalog.read(assert(catalog.pin()), nil, CLAUDE))
                test.eq(#selected.bindings, 2)
                test.eq(#assert(catalog.usable(selected)), 0)
            end)
            local restore = assert(registry.snapshot()):changes()
            restore:update(original)
            assert(restore:apply())
            if not ok then error(tostring(failure)) end
        end)
    end)
end
return test.run_cases(cases)
