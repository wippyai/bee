local test = require("test")
local identity = require("app_identity")

local WORKSPACE = "0123456789abcdef0123456789abcdef"
local OTHER_WORKSPACE = "fedcba9876543210fedcba9876543210"

local function define_tests()
    test.describe("Application stable identity", function()
        test.it("resolves one member for an admitted app across instances", function()
            local first = assert(identity.stable(WORKSPACE, "bee.example:app"))
            local second = assert(identity.stable(WORKSPACE, "bee.example:app"))
            test.eq(first.id, second.id)
            test.eq(first.workspace_id, WORKSPACE)
            test.eq(first.definition_id, "bee.example:app")
            test.is_nil(first.overlay_owner)
        end)
        test.it("separates another app, another workspace, and another overlay", function()
            local app = assert(identity.stable(WORKSPACE, "bee.example:app"))
            local other_app = assert(identity.stable(WORKSPACE, "bee.other:app"))
            local other_workspace = assert(identity.stable(OTHER_WORKSPACE, "bee.example:app"))
            local governed = assert(identity.stable(WORKSPACE, "app.research:app", "declared:overlay"))
            test.is_true(app.id ~= other_app.id)
            test.is_true(app.id ~= other_workspace.id)
            test.is_true(app.id ~= governed.id)
            test.eq(governed.overlay_owner, "declared:overlay")
            local colliding = assert(identity.stable(WORKSPACE, "app.research-app"))
            test.is_true(governed.id ~= colliding.id)
        end)
        test.it("preserves the existing governed identity with its declared owner", function()
            local stable = assert(identity.stable(WORKSPACE, "app.research:app", "bee.gov.apps:" .. WORKSPACE .. ".research"))
            test.eq(stable.id, "bee.application:0123456789abcdef0123456789abcdef:app.research-app-33a4adb51d88e2ad9183e853")
        end)
        test.it("uses admitted ownership independently of the definition spelling", function()
            local plain = assert(identity.stable(WORKSPACE, "app.research:app"))
            test.is_nil(plain.overlay_owner)
            local admitted = assert(identity.stable(WORKSPACE, "vendor.research:window", "declared:overlay"))
            test.eq(admitted.overlay_owner, "declared:overlay")
            test.is_true(admitted.id ~= assert(identity.stable(WORKSPACE, "vendor.research:window")).id)
            test.is_nil(identity.stable(WORKSPACE, "vendor.research:window", "bad\nowner"))
        end)
        test.it("keeps the workspace-prefixed actor shape without instance colons", function()
            local stable = assert(identity.stable(WORKSPACE, "bee.example:app"))
            test.eq(stable.id:sub(1, 16), "bee.application:")
            test.eq(stable.id:sub(17, 48), WORKSPACE)
            test.eq(stable.id:sub(49, 49), ":")
            test.is_nil((stable.id:sub(50):find(":", 1, true)))
            test.is_true(#stable.id <= 160)
        end)
        test.it("refuses unbounded or malformed admission values", function()
            test.is_nil(identity.stable("workspace", "bee.example:app"))
            test.is_nil(identity.stable(WORKSPACE, ""))
            test.is_nil(identity.stable(WORKSPACE, "bee.example:app\n"))
            test.is_nil(identity.stable(WORKSPACE, string.rep("d", 161)))
        end)
    end)
end

return require("test").run_cases(define_tests)
