local test = require("test")
local host = require("host")
local harness = require("harness")
local funcs = require("funcs")
local function define_tests()
    test.describe("Session hook invocation clocks", function()
        test.after_all(host.close_all)
        test.it("keeps a timely denial when wall time jumps forward during the supervised invocation", function()
            local session = host.open(nil, "bee.tests.memory:hooks_a")
            local reply = host.call("bee.threads.hooks:dispatch", {session_ref = session.session, thread_id = session.thread,
                workspace_id = host.WORKSPACE, point = "tool.before", occurrence_id = harness.key(), input = {mode = "clock_jump_deny"}})
            local _, reset_error = funcs.call("bee.tests.memory:advance_hook_clock", 0)
            test.is_nil(reset_error)
            local db = harness.open()
            local rows = harness.query(db, "SELECT diagnostic FROM bee_session_hook_invocations WHERE session_ref=?", {session.session})
            db:release()
            test.is_true(reply.denied, tostring(rows[1].diagnostic))
            test.eq(reply.reason, "timely denial across clock adjustment")
        end)
    end)
end
return test.run_cases(define_tests)
