local test = require("test")
local capability = require("capability")
local registry = require("registry")
local bounds = require("bounds")
local function cases()
    test.describe("Runtime process capability", function()
        test.it("uses native group admission without launching a shell or a probe executable", function()
            local original = assert(registry.get("bee.placement.native.env:executor_ref"))
            local changed = assert(registry.get("bee.placement.native.env:executor_ref"))
            assert(bounds.object(changed.data)).resource_ref = "bee.tests.placement.native.service:capability_executor"
            local changes = assert(registry.snapshot()):changes()
            changes:update(changed); assert(changes:apply())
            local ok, measurement = pcall(capability.measure)
            local restore = assert(registry.snapshot()):changes()
            restore:update(original); assert(restore:apply())
            test.is_true(ok)
            test.eq(measurement.capability, "process_group")
            test.eq(measurement.exit_observation, "independent")
            test.is_true(measurement.stdin_close)
        end)
    end)
end
return test.run_cases(cases)
