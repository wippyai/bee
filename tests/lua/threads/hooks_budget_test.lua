local test = require("test")
local host = require("host")
local harness = require("harness")
local bounds = require("bounds")
local capabilities = require("capabilities")
local response = require("response")
local funcs = require("funcs")
local supervisor = require("supervisor")
local process = require("process")
local events = require("events")
local channel = require("channel")
local security = require("security")
local function dispatch(session: host.Session, point: string, input: unknown?, output: unknown?, occurrence: string?): {[string]: unknown}
    return host.call("bee.threads.hooks:dispatch", {session_ref = session.session, thread_id = session.thread,
        workspace_id = host.WORKSPACE, point = point, occurrence_id = occurrence or harness.key(), input = input, output = output})
end
local function define_tests()
    test.describe("Session extension hooks", function()
        test.after_all(host.close_all)
        test.it("host supervision cancels an expired invocation and fences its late denial durably", function()
            local session = host.open(nil, "bee.tests.memory:hooks_a")
            local ready = assert(process.listen("bee.tests.hook.ready", {message = true}))
            local executor = funcs.new():with_actor(security.new_actor("memory-fixture-host", {workspace_id = host.WORKSPACE}))
            local occurrence = harness.key()
            local request = {session_ref = session.session, thread_id = session.thread, workspace_id = host.WORKSPACE,
                point = "tool.before", occurrence_id = occurrence, input = {mode = "held_deny", controller = tostring(process.pid())}}
            local future = assert(executor:async("bee.threads.hooks:dispatch", request))
            local held = assert(bounds.object(assert((ready:receive())):payload():data()))
            local cancelled = assert(events.subscribe("bee.test.hook/" .. assert(bounds.id(held.invocation_id)), "cancelled"))
            assert(future:response()):receive()
            local value, err = future:result()
            test.is_nil(err)
            test.is_false(host.value(assert(value):data()).denied)
            local cancellation = assert((cancelled:channel():receive()))
            test.is_true(assert(bounds.object(cancellation.data)).cancelled, "host cancels the app future")
            process.send(assert(bounds.id(held.pid)), "bee.tests.hook.release", {})
            local db = harness.open()
            local rows = harness.query(db, "SELECT state,diagnostic,reply_json FROM bee_session_hook_invocations WHERE invocation_id=?", {held.invocation_id})
            db:release()
            test.eq(rows[1].state, "diagnostic")
            test.eq(rows[1].diagnostic, "invocation budget exceeded")
            test.is_false(dispatch(session, "tool.before", request.input, nil, occurrence).denied)
            test.is_true(dispatch(session, "tool.before", {mode = "deny"}).denied)
            process.unlisten(ready)
            cancelled:close()
        end)
    end)
end
return test.run_cases(define_tests)
