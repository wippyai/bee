local test = require("test")
local view = require("view")
local forms = require("forms")
local appearance = require("appearance")
local function define_tests()
    test.describe("Agent allowance form", function()
        test.it("chooses a known bee and retains manually entered identities", function()
            local state = view.new("workspace", nil, {"fixture-peer"})
            local picker = state.form.fields[5]
            test.not_nil(picker)
            if not picker then return end
            forms.select_set(assert(picker.select), "fixture-peer")
            local intent = assert(view.intent(state))
            test.eq(assert(intent.request).peer, "fixture-peer")
            test.eq(intent.request.scope, "list")
            local shown = view.draw(120, 40, appearance.defaults(), state)
            local text = table.concat(shown.rows, "\n")
            test.contains(text, "Access")
            test.contains(text, "Known bee")
            test.is_nil((text:find("Allow agents he", 1, true)))
            view.input(state, {type = "key", action = "press", key_type = "runes", key = "-manual", ctrl = false, alt = false, shift = false}, shown)
            test.eq(forms.value(picker), "")
            test.eq(assert(view.intent(state)).request.peer, "fixture-peer-manual")
            forms.select_set(assert(picker.select), "")
            forms.text_set(assert(state.form.fields[1].text), "manual-peer")
            test.eq(assert(view.intent(state)).request.peer, "manual-peer")
        end)
    end)
end
return test.run_cases(define_tests)
