local test = require("test")
local form = require("form")
local appearance = require("appearance")
local function key(state: form.State, kind: string, value: string?)
    form.input(state, {type = "key", action = "press", key_type = kind, key = value or kind})
end
local function define_tests()
    test.describe("Start agent form", function()
        test.it("uses shared launch actions and normalized field hints", function()
            local shown = form.draw(120, 40, appearance.defaults(), form.new())
            local controls = assert(shown.controls)
            test.eq(#controls.buttons, 2)
            test.eq(controls.buttons[1].kind, "open")
            test.eq(controls.buttons[1].key, "Enter")
            test.eq(controls.buttons[1].label, "Start agent")
            test.contains(shown.rows[1], "START AGENT")
            test.eq(controls.buttons[2].kind, "cancel")
            test.eq(controls.buttons[2].key, "Esc")
            test.contains(table.concat(shown.rows, "\n"), "Tab field")
            for _, hit in ipairs(shown.hits) do
                if hit.kind == "open" then
                    test.eq(form.input(form.new(), {type = "mouse", action = "press", button = "left", x = hit.x, y = hit.y}, shown), "open")
                end
            end
        end)
        test.it("opens a name typed with a terminal space key", function()
            local state = form.new()
            key(state, "runes", "Driver")
            key(state, "space")
            key(state, "runes", "options")
            local value = assert(form.value(state))
            test.eq(value.name, "Driver options")
            local shown = form.draw(120, 30, appearance.defaults(), state)
            test.is_true(table.concat(shown.rows, "\n"):find("Name (optional): Driver options", 1, true) ~= nil)
            test.eq(form.input(state, {type = "key", action = "press", key_type = "enter", key = "enter"}), "open")
        end)
        test.it("edits pasted launch overrides through the text editor", function()
            local state = form.new()
            form.input(state, {type = "paste", text = "Launch name"})
            key(state, "tab")
            form.input(state, {type = "paste", text = "Builder role"})
            key(state, "left")
            key(state, "backspace")
            local value = assert(form.value(state))
            test.eq(value.name, "Launch name")
            test.eq(value.role, "Builder roe")
        end)
    end)
end
return test.run_cases(define_tests)
