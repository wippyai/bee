local test = require("test")
local exec = require("exec")
local identity = require("identity")
local function cases()
    test.describe("Linux process identity probe", function()
        test.it("reads the process group from procfs when ps is unavailable", function()
            local executor = assert(exec.get("bee.tests.speed:identity_executor"))
            local platform = assert(executor:exec("test -r /proc/self/stat"))
            assert(platform:start())
            if platform:wait() ~= 0 then executor:release(); return end
            local setup = assert(executor:exec("sh -c 'mkdir -p .wippy/speed-probe-bin; printf \"#!/bin/sh\\nexit 99\\n\" > .wippy/speed-probe-bin/ps; chmod +x .wippy/speed-probe-bin/ps'"))
            assert(setup:start()); test.eq(setup:wait(), 0)
            local child = assert(executor:exec("sh -c 'echo $$; read line'", {process_group = true}))
            local output = child:stdout_stream()
            local ok, failure = pcall(function()
                assert(child:start())
                local pid = math.floor(assert(tonumber(tostring(output:read(64)))))
                local recorded = assert(identity.read(executor, pid))
                test.eq(recorded.pgid, pid)
                test.not_nil(recorded.start_ticks)
                test.not_nil(recorded.boot_id)
            end)
            output:close(); child:close(true)
            local cleanup = assert(executor:exec("sh -c 'rm .wippy/speed-probe-bin/ps; rmdir .wippy/speed-probe-bin'"))
            assert(cleanup:start()); cleanup:wait()
            executor:release()
            if not ok then error(tostring(failure)) end
        end)
    end)
end
return test.run_cases(cases)
