local test = require("test")
local sql = require("sql")
local json = require("json")
local guard = require("guard")
local ledger = require("ledger")
local funcs = require("funcs")
local DB = "bee.tests.node:state_guard_db"
local function reset(): sql.DB
    local db = assert(sql.get(DB))
    assert(db:execute("DROP TABLE IF EXISTS _migrations"))
    assert(ledger.init_tracking_table(db))
    return db
end
local function applied(db: sql.DB, id: string)
    assert(ledger.record_migration(db, id, "fixture schema"))
end
local function define_tests()
    test.describe("Bee state schema compatibility", function()
        test.it("opens dev-labelled state on an alpha release with the same schema", function()
            local db = reset()
            applied(db, "fixture.migrations:one")
            assert(guard.record(db, "0.2.0-dev", "fixture", {"fixture.migrations:one"}))
            test.is_nil(guard.check(db, "/fixture", "0.2.0-alpha.5", {["fixture.migrations:one"] = true}))
            db:release()
        end)
        test.it("uses applied schema rather than the writer's available migration list", function()
            local db = reset()
            assert(guard.record(db, "999.0.0", "fixture", {"future.schema:unapplied"}))
            test.is_nil(guard.check(db, "/fixture", "0.2.0-alpha.5", {}))
            db:release()
        end)
        test.it("refuses an unknown ledger migration and names its writer", function()
            local db = reset()
            assert(guard.record(db, "0.2.0-alpha.4", "fixture", {}))
            applied(db, "future.schema:unknown")
            local message = guard.check(db, "/fixture", "0.2.0-alpha.5", {})
            test.not_nil(message)
            test.is_true(message ~= nil and message:find("was written by Bee 0.2.0-alpha.4", 1, true) ~= nil)
            test.is_true(message ~= nil and message:find("future.schema:unknown", 1, true) ~= nil)
            db:release()
        end)
        test.it("refuses an app database with an unknown migration before recording a writer", function()
            local db = reset()
            assert(guard.record(db, "0.2.0-dev", "fixture", {}))
            applied(db, "future.app:unknown")
            local before = assert(db:query("SELECT description FROM _migrations WHERE id = ?", {guard.WRITER}))
            db:release()
            local ok, message = guard.prepare(DB)
            test.is_nil(ok)
            test.is_true(message ~= nil and message:find("future.app:unknown", 1, true) ~= nil)
            db = assert(sql.get(DB))
            local after = assert(db:query("SELECT description FROM _migrations WHERE id = ?", {guard.WRITER}))
            test.eq(after[1].description, before[1].description)
            db:release()
        end)
        test.it("refuses a state format revision above binary support", function()
            local db = reset()
            applied(db, guard.WRITER)
            assert(db:execute("UPDATE _migrations SET description = ? WHERE id = ?",
                {assert(json.encode({version = "0.2.0-dev", build = "fixture", migrations = {}, format_revision = 2})), guard.WRITER}))
            local message = guard.check(db, "/fixture", "0.2.0-dev", {})
            test.is_true(message ~= nil and message:find("format revision 2", 1, true) ~= nil)
            db:release()
        end)
        test.it("opens older schema and applies its registered forward migration", function()
            local db = reset()
            local id = "bee.node.migrations:workspaces"
            assert(guard.record(db, "0.2.0-dev", "fixture", {}))
            test.is_nil(guard.check(db, "/fixture", "0.2.0-alpha.5", {[id] = true}))
            db:release()
            local result, problem = funcs.call(id, {target_db = "bee:db", database_id = DB, direction = "up", id = id})
            assert(not problem, tostring(problem))
            test.not_nil(result)
            db = assert(sql.get(DB))
            test.eq(#assert(db:query("SELECT id FROM _migrations WHERE id = ?", {id})), 1)
            test.eq(#assert(db:query("SELECT name FROM sqlite_master WHERE name = 'bee_node_workspaces'")), 1)
            db:release()
        end)
    end)
end
return test.run_cases(define_tests)
