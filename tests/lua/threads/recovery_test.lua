local process = require("process")
local channel = require("channel")
local time = require("time")
local test = require("test")
local recovery = require("recovery")
local runtime = require("runtime")
local function define_tests()
    test.describe("Thread commit recovery shutdown", function()
        test.it("exits recovery when its process is cancelled during settlement", function()
            local held = assert(process.listen("bee.test.recovery.held", {message = true}))
            local done = assert(process.listen("bee.test.recovery.done", {message = true}))
            local lifecycle = assert(process.events())
            local worker = assert(process.spawn_monitored("bee.tests.threads:recovery_worker", "bee:workers", tostring(process.pid())))
            local paused = channel.select({held:case_receive(), time.after("5s"):case_receive()})
            test.eq(paused.channel, held)
            assert(process.cancel(tostring(worker), "cancel recovery"))
            assert(process.send(tostring(worker), "bee.test.recovery.resume", {}))
            local finished = channel.select({done:case_receive(), time.after("5s"):case_receive()})
            test.eq(finished.channel, done)
            local result = finished.value:payload():data()
            assert(type(result) == "table")
            test.eq(result.settled, 1)
            test.eq(result.announced, 0)
            test.eq(result.released, 1)
            local exited = channel.select({lifecycle:case_receive(), time.after("5s"):case_receive()})
            test.eq(exited.channel, lifecycle)
            test.eq(exited.value.kind, process.event.EXIT)
            test.eq(tostring(exited.value.from), tostring(worker))
            test.eq(exited.value.result.error, nil)
            lifecycle:close()
            process.unlisten(held)
            process.unlisten(done)
        end)
        test.it("does no store work after cancellation", function()
            runtime.reset()
            runtime.cancelled = true
            recovery.recover(runtime.active)
            test.eq(runtime.opened, 0)
            test.eq(runtime.reads, 0)
        end)
        test.it("cancels between settlement and announcement and releases the store", function()
            runtime.reset()
            runtime.cancel_on_settle = true
            recovery.recover(runtime.active)
            test.eq(runtime.settled, 1)
            test.eq(runtime.announced, 0)
            test.eq(runtime.released, 1)
        end)
        test.it("releases the store when a recovery read fails", function()
            runtime.reset()
            runtime.query_error = true
            local ok, problem = pcall(recovery.recover, runtime.active)
            test.eq(ok, false)
            test.is_true(tostring(problem):find("injected read failure", 1, true) ~= nil)
            test.eq(runtime.released, 1)
        end)
        test.it("releases the store when settlement fails", function()
            runtime.reset()
            runtime.settle_error = true
            local ok, problem = pcall(recovery.recover, runtime.active)
            test.eq(ok, false)
            test.is_true(tostring(problem):find("injected settlement failure", 1, true) ~= nil)
            test.eq(runtime.released, 1)
        end)
    end)
end
return test.run_cases(define_tests)
